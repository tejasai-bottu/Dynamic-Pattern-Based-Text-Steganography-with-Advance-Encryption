def print_profiles() -> None:
    safe_bps = math.log2(len(_SAFE_CHARS))
    print(f"\n  {'ID':<4} {'Profile':<12} {'Chars':>6} {'Bits/sym':>10} {'vs SAFE':>9}  Status")
    print(f"  {'─'*4} {'─'*12} {'─'*6} {'─'*10} {'─'*9}  {'─'*48}")
    for pid in (PROFILE_SAFE, PROFILE_EXTENDED, PROFILE_MAX):
        info   = profile_info(pid)
        mult   = info["bits_per_sym"] / safe_bps
        status = PROFILE_STATUS[pid]
        print(
            f"  {pid:<4} {info['name']:<12} {info['size']:>6} "
            f"{info['bits_per_sym']:>10.3f} {mult:>8.2f}×  {status}"
        )
    print(f"\n  Length prefix: {_PREFIX_SYMS} symbols (fixed, SAFE alphabet, unkeyed)")
    print(f"  Format version: {_VERSION}")
    print()


def estimate_cover_chars(file_bytes: int, profile_id: int,
                         compression_ratio: float = 0.65) -> int:
    """
    Estimate minimum cover text character count for the given file size.
    compression_ratio: assumed fraction after zlib (0.65 is conservative).
    """
    n_alpha = len(_get_profile_chars(profile_id))
    # header overhead (conservative): ~60 bytes
    payload = int(file_bytes * compression_ratio) + 60
    n_syms  = _num_symbols(payload, n_alpha) + _PREFIX_SYMS   # §3 — exact
    return n_syms + 2   # need n_syms gaps → n_syms+1 chars minimum, +1 safety


# -----------------------------------------------------------------------------
# Stage 0 self-test — Unicode alphabet validation
# -----------------------------------------------------------------------------

def test_unicode_alphabets(verbose: bool = True) -> bool:
    """
    Stage 0: Validate all three Unicode alphabet profiles.

    Checks (per profile and per character):
      1.  Correct character counts (11 / 55 / 392)
      2.  No duplicates within any profile
      3.  Subset relationships: SAFE ⊆ EXTENDED ⊆ MAX
      4.  Correct tier assignments (T1 in SAFE, T1+T2 in EXTENDED, etc.)
      5.  UTF-8 encode/decode identity for every character
      6.  UTF-8 file write/read identity for every character
      7.  Python string-op stability (len, split, replace, strip)
      8.  SAFE characters all in expected Unicode categories (Cf or Mn)
      9.  _ALL_STEGO_CHARS coverage (extraction set == MAX set)
      10. NFKC stability: SAFE must pass (critical); EXTENDED instability
          for U+3164/U+FFA0 is reported as a WARNING, not a hard failure.

    Returns True only if all hard checks pass.
    U+3164 and U+FFA0 NFKC warnings are informational only.
    """
    EXPECTED_COUNTS = {
        PROFILE_SAFE:     11,
        PROFILE_EXTENDED: 55,
        PROFILE_MAX:      392,
    }

    # Characters known to fail NFKC/NFKD (score 11/13) — kept deliberately in
    # Tier 2/EXTENDED but must not be used in NFKC-normalising environments.
    NFKC_UNSTABLE = {"\u3164", "\uFFA0"}  # U+3164 and U+FFA0 → U+1160

    print("\n  ── STAGE 0: UNICODE ALPHABET VALIDATION ─────────────────────────────────")
    print(f"  Profiles : SAFE ({EXPECTED_COUNTS[PROFILE_SAFE]}) · "
          f"EXTENDED ({EXPECTED_COUNTS[PROFILE_EXTENDED]}) · "
          f"MAX ({EXPECTED_COUNTS[PROFILE_MAX]})")
    print(f"  Checks   : counts · uniqueness · subset · tiers · UTF-8 "
          f"· file I/O · string-ops · categories")
    print()

    all_ok   = True
    failures: list = []

    def fail(msg: str) -> None:
        nonlocal all_ok
        all_ok = False
        failures.append(msg)

    # ── Check 1: counts ────────────────────────────────────────────────────
    for pid, expected in EXPECTED_COUNTS.items():
        actual = len(_PROFILE_CHARS[pid])
        if actual != expected:
            fail(f"Count mismatch {PROFILE_NAMES[pid]}: "
                 f"expected {expected}, got {actual}")
    print(f"  [{'✓' if all_ok else '✗'}] Counts: "
          f"SAFE={len(_SAFE_CHARS)}  EXTENDED={len(_EXTENDED_CHARS)}  MAX={len(_MAX_CHARS)}")

    # ── Check 2: uniqueness ────────────────────────────────────────────────
    ok2 = True
    for pid in (PROFILE_SAFE, PROFILE_EXTENDED, PROFILE_MAX):
        lst = _PROFILE_CHARS[pid]
        dupes = len(lst) - len(set(lst))
        if dupes:
            fail(f"Duplicates in {PROFILE_NAMES[pid]}: {dupes} duplicate(s)")
            ok2 = False
    print(f"  [{'✓' if ok2 else '✗'}] No duplicates in any profile")

    # ── Check 3: subset relationships ──────────────────────────────────────
    safe_set = frozenset(_SAFE_CHARS)
    ext_set  = frozenset(_EXTENDED_CHARS)
    max_set  = frozenset(_MAX_CHARS)
    ok3 = safe_set <= ext_set and ext_set <= max_set
    if not (safe_set <= ext_set):
        fail(f"SAFE not a subset of EXTENDED: "
             f"extra {[hex(ord(c)) for c in safe_set - ext_set]}")
    if not (ext_set <= max_set):
        fail(f"EXTENDED not a subset of MAX: "
             f"extra {[hex(ord(c)) for c in ext_set - max_set]}")
    print(f"  [{'✓' if ok3 else '✗'}] SAFE ⊆ EXTENDED ⊆ MAX")

    # ── Check 4: tier assignments ──────────────────────────────────────────
    ok4 = True
    # All SAFE chars must be T1
    for ch in _SAFE_CHARS:
        if _CHAR_TIERS.get(ch) != TIER_RELIABLE:
            fail(f"Non-T1 char in SAFE: U+{ord(ch):04X}")
            ok4 = False
    # EXTENDED-only chars must be T2
    for ch in _EXTENDED_CHARS:
        if ch not in safe_set:
            t = _CHAR_TIERS.get(ch)
            if t != TIER_GOOD:
                fail(f"Unexpected tier {t} for EXTENDED-only char U+{ord(ch):04X}")
                ok4 = False
    # MAX-only chars must be T3
    for ch in _MAX_CHARS:
        if ch not in ext_set:
            t = _CHAR_TIERS.get(ch)
            if t != TIER_EXPERIMENTAL:
                fail(f"Unexpected tier {t} for MAX-only char U+{ord(ch):04X}")
                ok4 = False
    t1 = sum(1 for t in _CHAR_TIERS.values() if t == TIER_RELIABLE)
    t2 = sum(1 for t in _CHAR_TIERS.values() if t == TIER_GOOD)
    t3 = sum(1 for t in _CHAR_TIERS.values() if t == TIER_EXPERIMENTAL)
    print(f"  [{'✓' if ok4 else '✗'}] Tier assignments correct: "
          f"T1={t1}  T2={t2}  T3={t3}")

    # ── Check 5: UTF-8 encode/decode identity ─────────────────────────────
    ok5 = True
    for ch in _MAX_CHARS:
        try:
            if ch.encode("utf-8").decode("utf-8") != ch:
                fail(f"UTF-8 round-trip failed for U+{ord(ch):04X}")
                ok5 = False
        except Exception as exc:
            fail(f"UTF-8 encode error for U+{ord(ch):04X}: {exc}")
            ok5 = False
    print(f"  [{'✓' if ok5 else '✗'}] UTF-8 encode/decode identity ({len(_MAX_CHARS)} chars)")

    # ── Check 6: file write/read round-trip (UTF-8) ────────────────────────
    ok6 = True
    try:
        sample = "".join(_MAX_CHARS)
        with tempfile.NamedTemporaryFile(
                mode="w", suffix=".txt", encoding="utf-8",
                delete=False) as tf:
            tf.write(sample)
            fpath = tf.name
        with open(fpath, "r", encoding="utf-8") as fh:
            recovered = fh.read()
        os.remove(fpath)
        if recovered != sample:
            # Find which char(s) changed
            lost = [ch for ch in _MAX_CHARS if ch not in recovered]
            fail(f"File UTF-8 round-trip lost {len(lost)} chars: "
                 f"{[hex(ord(c)) for c in lost[:5]]}")
            ok6 = False
    except Exception as exc:
        fail(f"File write/read test error: {exc}")
        ok6 = False
    print(f"  [{'✓' if ok6 else '✗'}] UTF-8 file write/read identity "
          f"({'all ' + str(len(_MAX_CHARS)) + ' chars survived' if ok6 else 'FAILED'})")

    # ── Check 7: Python string-op stability ────────────────────────────────
    ok7 = True
    for ch in _MAX_CHARS:
        try:
            s = f"A{ch}B"
            if len(s) != 3:
                fail(f"len() wrong for U+{ord(ch):04X}: {len(s)} != 3")
                ok7 = False
                continue
            if s.replace(ch, "") != "AB":
                fail(f"replace() failed for U+{ord(ch):04X}")
                ok7 = False
            if s.split(ch) != ["A", "B"]:
                fail(f"split() failed for U+{ord(ch):04X}")
                ok7 = False
        except Exception as exc:
            fail(f"String-op error U+{ord(ch):04X}: {exc}")
            ok7 = False
    print(f"  [{'✓' if ok7 else '✗'}] Python string ops (len/replace/split) stable")

    # ── Check 8: SAFE chars are Cf or Mn (correct Unicode categories) ──────
    ok8 = True
    allowed_cats = {"Cf", "Mn"}
    for ch in _SAFE_CHARS:
        cat = unicodedata.category(ch)
        if cat not in allowed_cats:
            fail(f"Unexpected category {cat!r} for SAFE char U+{ord(ch):04X}")
            ok8 = False
    print(f"  [{'✓' if ok8 else '✗'}] SAFE chars all in expected Unicode categories "
          f"(Cf/Mn)")

    # ── Check 9: _ALL_STEGO_CHARS equals MAX set ───────────────────────────
    ok9 = (_ALL_STEGO_CHARS == max_set)
    if not ok9:
        extra   = _ALL_STEGO_CHARS - max_set
        missing = max_set - _ALL_STEGO_CHARS
        if extra:   fail(f"_ALL_STEGO_CHARS has {len(extra)} extra chars")
        if missing: fail(f"_ALL_STEGO_CHARS missing {len(missing)} chars")
    print(f"  [{'✓' if ok9 else '✗'}] _ALL_STEGO_CHARS == MAX set "
          f"({len(_ALL_STEGO_CHARS)} chars)")

    # ── Check 10: NFKC stability — SAFE must be stable; warn for EXTENDED ──
    ok10_safe = True
    for ch in _SAFE_CHARS:
        normed = unicodedata.normalize("NFKC", ch)
        if normed != ch:
            fail(f"SAFE char U+{ord(ch):04X} changes under NFKC → "
                 f"U+{ord(normed):04X}")
            ok10_safe = False
    print(f"  [{'✓' if ok10_safe else '✗'}] SAFE chars all NFKC-stable "
          f"(critical: prefix uses SAFE alphabet)")

    # Informational: which EXTENDED chars are NFKC-unstable (does NOT fail Stage 0)
    nfkc_unstable_ext = []
    for ch in _EXTENDED_CHARS:
        normed = unicodedata.normalize("NFKC", ch)
        if normed != ch:
            nfkc_unstable_ext.append((ch, normed))
    if nfkc_unstable_ext:
        print(f"  [⚠] EXTENDED has {len(nfkc_unstable_ext)} NFKC-unstable "
              f"char(s) — known, deliberate, documented:")
        for ch, normed in nfkc_unstable_ext:
            print(f"      U+{ord(ch):04X} → U+{ord(normed[0]):04X}  "
                  f"(avoid EXTENDED in NFKC-normalising environments)")
    else:
        print(f"  [✓] No NFKC-unstable chars in EXTENDED")

    # ── Summary ────────────────────────────────────────────────────────────
    print()
    if all_ok:
        print("  Stage 0 PASSED ✓  (10/10 check groups, 0 failures)")
    else:
        print(f"  Stage 0 FAILED ✗  ({len(failures)} failure(s)):")
        for msg in failures:
            print(f"    • {msg}")
    print()
    return all_ok


