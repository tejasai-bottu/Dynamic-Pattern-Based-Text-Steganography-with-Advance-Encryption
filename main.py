def _interactive_menu() -> None:
    print(_BANNER)
    print()
    print("  [1]  Encrypt file  →  stego text")
    print("  [2]  Decrypt stego text  →  original file")
    print("  [3]  Profile & capacity info")
    print("  [4]  Full self-test  (Stage 0 Unicode + Stage 1 base-N + Stage 2 round-trip)")
    print("  [5]  Stage 0 only: Unicode alphabet validation")
    print("  [6]  Stage 1 only: base-N arithmetic test")
    print("  [Q]  Quit")
    choice = input("\n  Choice: ").strip().upper()

    dispatch = {
        "1": _menu_encrypt,
        "2": _menu_decrypt,
        "3": _menu_info,
        "4": lambda: self_test(verbose=True),
        "5": lambda: test_unicode_alphabets(verbose=True),
        "6": lambda: test_base_n(verbose=True),
    }
